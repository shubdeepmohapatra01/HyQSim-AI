/**
 * `npm run ai:gatespec` — exports the gate catalogue and a set of HQC golden cases to
 * `shared/`, where the Python side reads them.
 *
 * HQC has two implementations: `frontend/src/ai/hqc.ts` for the in-app chat, and
 * `backend/simulation/hqc.py` for the MCP server. Hand-maintaining the gate catalogue in
 * both would drift the moment anyone adds a gate, and the failure would be silent — the
 * MCP server would just refuse a gate the UI offers. So TypeScript owns the catalogue,
 * Python consumes it, and a test asserts the committed file is current.
 */

import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ALL_GATES } from '../../types/circuit';
import { GATE_ALIASES, PYTHON_BACKEND_GATES, decodeCircuit, encodeCircuit } from '../hqc';

const HERE = dirname(fileURLToPath(import.meta.url));
export const SHARED_DIR = join(HERE, '..', '..', '..', '..', 'shared');

export function buildGateSpec() {
  return {
    $comment: 'GENERATED by `npm run ai:gatespec` from frontend/src/types/circuit.ts. Do not edit by hand.',
    gates: ALL_GATES.map(g => ({
      id: g.id,
      name: g.name,
      category: g.category,
      numQubits: g.numQubits ?? 0,
      numQumodes: g.numQumodes ?? 0,
      parameters: (g.parameters ?? []).map(p => ({
        name: p.name,
        defaultValue: p.defaultValue,
      })),
      pythonBackend: PYTHON_BACKEND_GATES.has(g.id),
    })),
    aliases: GATE_ALIASES,
  };
}

/** Circuits both implementations must encode and decode identically. */
const GOLDEN_SOURCES = [
  'W q0 q1\nG h q0; cnot q0>q1',
  'W q0 q1 q2 q3\nG h q0; cnot q0>q1; cnot q1>q2; cnot q2>q3',
  'W q0 m0\nG h q0; cdisp q0>m0 2,0',
  'W m0\nG squeeze m0 0.8,0',
  'W m0\nG rotate m0 pi/2',
  'W m0 m1\nG squeeze m0 0.8,0; squeeze m1 0.8,pi; bs m0>m1 pi/4,0',
  'W q0=+ m0=2\nG (none)',
  'W q0 m0\nG jc q0>m0 pi/4',
  'W m0\nG displace m0 1.5,-0.5; kerr m0 0.2',
  'W q0 q1 q2\nG h q0; cnot q0>q1; cnot q1>q2; measure q0; measure q1; measure q2',
  'W q0 m0\nG rx q0 pi/3; cr q0>m0 pi/8; xcdisp q0>m0 1,1',
];

/** Malformed inputs both implementations must reject, with a reason mentioning `contains`. */
const GOLDEN_ERRORS = [
  { source: 'W q0\nG flurb q0', contains: 'flurb' },
  { source: 'W q0 m0\nG h m0', contains: 'qubit' },
  { source: 'W q0 m0\nG cdisp m0>q0 2,0', contains: 'qubit' },
  { source: 'W q0 q1\nG cnot q0', contains: 'two wires' },
  { source: 'W q0 q1\nG cnot q0>q0', contains: 'distinct' },
  { source: 'W q0\nG h q7', contains: 'q7' },
  { source: 'W x9\nG (none)', contains: 'wire label' },
];

export function buildGoldenCases() {
  return {
    $comment: 'GENERATED by `npm run ai:gatespec`. Shared fixtures for hqc.ts and hqc.py.',
    roundTrip: GOLDEN_SOURCES.map(source => {
      const { wires, elements, errors } = decodeCircuit(source);
      if (errors.length > 0) throw new Error(`Golden source failed to decode: ${source}\n${errors.join('\n')}`);
      return {
        source,
        encoded: encodeCircuit(wires, elements),
        wires: wires.map(w => ({ type: w.type, index: w.index, initialState: w.initialState ?? null })),
        gates: [...elements]
          .sort((a, b) => a.position.x - b.position.x)
          .map(e => ({
            gateId: e.gateId,
            wireIndex: e.wireIndex,
            targetWireIndices: e.targetWireIndices ?? null,
            parameterValues: e.parameterValues ?? {},
          })),
      };
    }),
    errors: GOLDEN_ERRORS,
  };
}

function main() {
  mkdirSync(SHARED_DIR, { recursive: true });
  writeFileSync(join(SHARED_DIR, 'gates.json'), JSON.stringify(buildGateSpec(), null, 2) + '\n');
  writeFileSync(join(SHARED_DIR, 'hqc_cases.json'), JSON.stringify(buildGoldenCases(), null, 2) + '\n');
  console.log(`Wrote gates.json and hqc_cases.json to ${SHARED_DIR}`);
}

// Only run when invoked directly, not when imported by the drift test.
if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop()!)) {
  main();
}
